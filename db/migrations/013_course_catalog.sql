-- Course catalog that Labb admins edit at /admin/courses: name, overview, price, pages, CPP access and status.
-- Course files and what is built into them (chapters, questions, pass mark) live in code (lib/courses.ts).
-- status: live = listed and for sale, coming = listed as coming soon, draft = hidden (admins can preview).
create table if not exists courses (
  slug          text primary key,
  title         text not null,
  short         text not null,
  type          text not null check (type in ('position', 'product', 'software', 'specimen')),
  overview      text not null default '',
  for_who       text not null default '',
  price_cents   integer check (price_cents is null or price_cents >= 0),
  pages         integer check (pages is null or pages > 0),
  cpp_included  boolean not null default false,
  status        text not null default 'draft' check (status in ('live', 'coming', 'draft')),
  sort          integer not null default 100,
  updated_by    uuid references members(id) on delete set null,
  updated_at    timestamptz not null default now()
);

