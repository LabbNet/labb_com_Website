- Share the **industry editions of the Employers Guidebook** with clients in construction, manufacturing, logistics, healthcare and hospitality, so each client gets guidance written for its own workforce.
- Use the **Drug Testing Cost Guidebook** when clients ask what their program should cost and why.
- Point collection partners to the **clinic training library** so collections are handled the same way across your network.

