## For clinics and collection sites

Clinics and collection sites are where testing actually happens, so their guidebooks go deeper into the technical side.

- **Clinic Owners Guidebook:** written for clinic owners, operators and collectors. A complete drug testing manual covering rapid and lab testing, the MRO process, collections, reading package inserts, quality control, privacy, alcohol testing and drug classes. It is updated every quarter so the content stays current.
- **Background Screening Guidebook:** the companion to the Clinic Owners Guidebook. Explains how background checks work and what the law requires before a clinic offers them to customers.

The clinic training library is available to members of Labb's [Channel Partner Program](/channel-partner-program). If your clinic or collection site is not a member yet, you can learn about the program and register there.

## For TPAs

